// This is Good comparison
console.log(2 > 1);
console.log(2 < 1);
console.log(2 >= 1);
console.log(2 <=  1);
console.log(2 == 1);
console.log(2 != 1);

// This is Bad comparison
console.log("2" > 1);
console.log(1 < "2");

console.log(null > 0);
console.log(null == 0);
console.log(null >= 0);
console.log(null <= 0);
console.log(null != 0);

console.log(undefined > 0);
console.log(undefined == 0);
console.log(undefined >= 0);
console.log(undefined <= 0);
console.log(undefined != 0);

// === strict equality operator 
console.log("2" === 2);






